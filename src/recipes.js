function buildCollectibleRecipes(seedIngredients) {
  const outputs = buildCollectibleOutputs();
  const out = [];

  // 为每个输出元素稳定地分配一个“配方对”（保证离线可达 + 不依赖深层链路）
  for (const result of outputs) {
    const a = pickByHash(result + ":a", seedIngredients);
    let b = pickByHash(result + ":b", seedIngredients);
    if (b === a) b = pickByHash(result + ":b2", seedIngredients);
    out.push([a, b, result]);
  }

  return out;
}

export function buildRecipeBook() {
  const map = new Map();

  const add = (a, b, r) => {
    if (!a || !b || !r) return;
    const key = stablePairKey(a, b);
    if (!map.has(key)) map.set(key, r);
  };

  // 主线配方
  for (const [a, b, r] of CORE) add(a, b, r);

  // 关键种子（用于大量收藏向配方的“原料池”）
  const seedIngredients = uniq([
    "金", "木", "水", "火", "土",
    "蒸汽", "泥", "岩浆", "石头", "沙", "玻璃",
    "云", "雨", "风", "闪电", "彩虹", "雷暴",
    "海", "山", "森林", "岛", "峡谷",
    "种子", "植物", "树", "花", "蜂蜜", "海藻", "盐",
    "金属", "工具", "锤子", "扳手", "熔炉", "钢", "齿轮",
    "房子", "村庄", "城市", "科技", "魔法",
    "生命", "动物", "宠物", "萌宠",
    "寒冷", "冰", "雪",
    "麦", "面包",
  ]);

  // 收藏向 1000+ 配方
  for (const [a, b, r] of buildCollectibleRecipes(seedIngredients)) add(a, b, r);

  return map;
}
